    { key = "Salt",      sub = "salt",      group = "Common" },
    { key = "WaterSlug", sub = "waterslug", group = "Common" },
    -- Medium
    { key = "Lead",      sub = "lead",      group = "Medium" },
    { key = "Silver",    sub = "silver",    group = "Medium" },
    { key = "Sulfur",    sub = "sulfur",    group = "Medium" },
    { key = "Gold",      sub = "gold",      group = "Medium" },
